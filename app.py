import gradio as gr
import pickle
import numpy as np

model = pickle.load(open("model.pkl","rb"))

def predict(
    loan_amnt, term, int_rate, installment, grade, sub_grade,
    annual_inc, verification_status, dti, earliest_cr_line,
    open_acc, total_acc, revol_bal, revol_util, all_util,
    acc_now_delinq, mths_since_last_delinq, pub_rec,
    collections_12_mths_ex_med, inq_last_6mths, inq_last_12m,
    tot_cur_bal, total_rev_hi_lim, home_ownership
):

    data = np.array([[loan_amnt, term, int_rate, installment, grade, sub_grade,
                      annual_inc, verification_status, dti, earliest_cr_line,
                      open_acc, total_acc, revol_bal, revol_util, all_util,
                      acc_now_delinq, mths_since_last_delinq, pub_rec,
                      collections_12_mths_ex_med, inq_last_6mths, inq_last_12m,
                      tot_cur_bal, total_rev_hi_lim, home_ownership]])

    pred = model.predict(data)[0]

    if pred == 1:
        return "⚠️ High Risk of Delinquency"
    else:
        return "✅ Low Risk of Delinquency"


